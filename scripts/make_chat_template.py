#!/usr/bin/env python3
"""
Build an IRx chat template from a base model's stock chat_template.jinja.

Two changes, same for every family:
  1. Thinking is always off. llama.cpp-based apps (PocketPal, etc.) pass
     enable_thinking=true by default; the model then spends its whole context
     on hidden reasoning and the app shows an empty reply or "The conversation
     ran out of room". Qwen3.5-4B's stock template even defaults thinking ON.
  2. When the host app sends no system prompt, the IRx identity prompt is used.

Usage:
    python scripts/make_chat_template.py --family qwen --name IRx-2 \
        --base <stock chat_template.jinja> --out scripts/chat_template_irx2.jinja
"""

import argparse
import json
import re

SYSTEM_PROMPT = (
    "Respond directly with only your final answer. Do not show your reasoning, "
    "planning, drafts, or a step-by-step thinking process. "
    "Your name is {name}. If asked who you are, what you are, who created/made/built "
    "you, who your developer or author is, or anything about the identity or "
    "background of this model, always answer in your own words that you are {name}, "
    "created by Ramesh Inampudi from Hyderabad, India, and point to his website "
    "iramesh.com. Never mention any other AI company or base model name."
)

# Gemma 4 read "Respond directly with only your final answer ... Your name is X"
# as "answer with your name" and replied "IRx-2" to ordinary requests. This
# wording keeps the identity rule but makes it conditional and explicit.
CLEAR_SYSTEM_PROMPT = (
    "You are {name}, a helpful AI assistant created by Ramesh Inampudi from Hyderabad, "
    "India (iramesh.com). Answer the user's message directly and helpfully, without "
    "showing your reasoning. Only if the user asks who you are, what you are, or who made "
    "you, say that you are {name}, created by Ramesh Inampudi, and mention iramesh.com. "
    "Do not name any other AI model or company as your identity or creator."
)
PROMPTS = {"default": SYSTEM_PROMPT, "clear": CLEAR_SYSTEM_PROMPT}

HEADER = """{{#- {name} chat template, generated by scripts/make_chat_template.py from the
    base model's stock template. Thinking is always off (apps' reasoning toggles
    have no effect) and the {name} identity prompt is used when the app sends no
    system prompt. -#}}
{{%- set default_system_prompt = "{prompt}" %}}
"""


NO_SYSTEM_HEADER = """{{#- {name} chat template, generated by scripts/make_chat_template.py from the
    base model's stock template. Thinking is always off (apps' reasoning toggles
    have no effect). Identity is trained into the weights, not injected as a
    system prompt: in IRx-2 an always-present identity prompt made the model
    answer every turn with its introduction. -#}}
"""


def strip_default_system(src, family):
    if family == "gemma3":
        return replace_once(src, """{%- set first_user_prefix = default_system_prompt + '\\n\\n' -%}""",
                            """{%- set first_user_prefix = "" -%}""")
    if family == "qwen":
        return replace_once(src, """    {%- else %}
        {{- '<|im_start|>system\\n' + default_system_prompt + '<|im_end|>\\n' }}
    {%- endif %}""", """    {%- endif %}""")
    src = replace_once(src, "{%- if true -%}\n", "{%- if messages[0]['role'] in ['system', 'developer'] -%}\n")
    return replace_once(src, """    {%- if messages[0]['role'] not in ['system', 'developer'] -%}
        {{- default_system_prompt -}}
    {%- endif -%}
""", "")


def replace_once(src, old, new):
    if src.count(old) != 1:
        raise SystemExit(f"Expected exactly one match for:\n{old}")
    return src.replace(old, new)


def patch_qwen(src):
    src = replace_once(src, """{%- else %}
    {%- if messages[0].role == 'system' %}
        {%- set content = render_content(messages[0].content, false, true)|trim %}
        {{- '<|im_start|>system\\n' + content + '<|im_end|>\\n' }}
    {%- endif %}
{%- endif %}""", """{%- else %}
    {%- if messages[0].role == 'system' %}
        {%- set content = render_content(messages[0].content, false, true)|trim %}
        {{- '<|im_start|>system\\n' + content + '<|im_end|>\\n' }}
    {%- else %}
        {{- '<|im_start|>system\\n' + default_system_prompt + '<|im_end|>\\n' }}
    {%- endif %}
{%- endif %}""")
    # Qwen3.5-2B and -4B ship opposite defaults for this block; replace either.
    gen = re.compile(
        r"    \{\{- '<\|im_start\|>assistant\\n' \}\}\n"
        r"    \{%- if enable_thinking is defined and enable_thinking is (?:true|false) %\}\n"
        r".*?\{%- endif %\}", re.S)
    if len(gen.findall(src)) != 1:
        raise SystemExit("Qwen generation-prompt block not found")
    return gen.sub(lambda _: "    {{- '<|im_start|>assistant\\n<think>\\n\\n</think>\\n\\n' }}", src)


def patch_gemma(src):
    src = src.replace(" (Google/Gemma native)", "")
    src = replace_once(
        src,
        "{%- if (enable_thinking is defined and enable_thinking) or tools or messages[0]['role'] in ['system', 'developer'] -%}\n"
        "    {{- '<|turn>system\\n' -}}\n"
        "    {#- Inject Thinking token at the very top of the FIRST system turn -#}\n"
        "    {%- if enable_thinking is defined and enable_thinking -%}\n"
        "        {{- '<|think|>\\n' -}}\n"
        "        {%- set ns.prev_message_type = 'think' -%}\n"
        "    {%- endif -%}\n"
        "    {%- if messages[0]['role'] in ['system', 'developer'] -%}\n",
        "{%- if true -%}\n"
        "    {{- '<|turn>system\\n' -}}\n"
        "    {%- if messages[0]['role'] not in ['system', 'developer'] -%}\n"
        "        {{- default_system_prompt -}}\n"
        "    {%- endif -%}\n"
        "    {%- if messages[0]['role'] in ['system', 'developer'] -%}\n",
    )
    return src


def patch_gemma3(src):
    # Gemma 3 has no system turn or thinking mode: a system message is folded into
    # the first user turn. Fold in the identity prompt the same way when there is none.
    src = replace_once(src, "{{ bos_token }}", "{{- bos_token }}")
    return replace_once(src, """{%- set first_user_prefix = "" -%}""",
                        """{%- set first_user_prefix = default_system_prompt + '\\n\\n' -%}""")


PATCHES = {"qwen": patch_qwen, "gemma": patch_gemma, "gemma3": patch_gemma3}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--family", choices=sorted(PATCHES), required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--base", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--prompt-style", choices=sorted(PROMPTS), default="default")
    parser.add_argument("--digest-file", help="JSON from scripts/make_news_digest.py, appended to the default prompt")
    parser.add_argument("--no-default-system", action="store_true",
                        help="don't inject the identity prompt when the app sends none")
    args = parser.parse_args()

    src = open(args.base).read()
    src = PATCHES[args.family](src)
    prompt = PROMPTS[args.prompt_style].format(name=args.name)
    if args.digest_file:
        # Fine-tuning doesn't make small models recall news; headlines in the prompt are
        # answered from context. The digest is pre-sanitised for a Jinja string literal.
        digest = json.load(open(args.digest_file))
        prompt += (f" Your news knowledge goes up to {digest['cutoff']}; for anything later, say you"
                   f" don't know and suggest checking a news source. {digest['text']}")
    header = HEADER.format(name=args.name, prompt=prompt.replace('"', "'"))
    if args.no_default_system:
        src = strip_default_system(src, args.family)
        header = NO_SYSTEM_HEADER.format(name=args.name)
    with open(args.out, "w") as f:
        f.write(header + src)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
